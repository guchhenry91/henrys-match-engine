"""Run the Champions League walk-forward backtest and write the report.

SKIPPED WHEN NOTHING IT READS HAS CHANGED (owner, 2026-10-26, Cloudflare bill). The
gate is deterministic -- finished matches in, report out -- yet ran on all ~33 soccer
refreshes a day at ~4 minutes each, over a third of every run's container time. The
report now carries a fingerprint of its inputs (the finished matches and the code that
scores them); a run whose fingerprint matches the report's is a no-op. A new result,
an override or a code change re-runs it as before.
"""
import hashlib
import json
import sys
from pathlib import Path

from ucl import backtest, data

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data-raw" / "ucl" / "backtest_report.json"
CODE = ("ucl/backtest.py", "ucl/config.py", "ucl/data.py", "leagues/model.py")


def fingerprint(frame) -> str:
    h = hashlib.sha256(frame.to_csv(index=False).encode("utf-8"))
    for rel in CODE:
        h.update((ROOT / rel).read_bytes())
    return h.hexdigest()


def up_to_date(fp) -> bool:
    try:
        return json.loads(OUT.read_text(encoding="utf-8")).get("_inputs") == fp
    except Exception:
        return False


def main():
    frame = data.matches()
    if frame.empty:
        print("no cached history; run scripts.sync_ucl_history first")
        return 0
    fp = fingerprint(frame)
    if up_to_date(fp):
        print(f"no new matches or code since the last gate run ({len(frame)} matches); report kept")
        return 0
    result = backtest.evaluate(backtest.walk_forward(frame))
    result["_inputs"] = fp
    result["_note"] = ("Walk-forward Champions League backtest. Every scored "
                       "season is one the model never saw. Generated by "
                       "scripts/ucl_backtest.py -- do not hand-edit.")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")

    overall = result.get("overall", {})
    print(f"n={overall.get('n')}  RPS {overall.get('rps')} vs baseline "
          f"{overall.get('rps_baseline')}  accuracy {overall.get('accuracy')}  "
          f"RELEASED={result['released']}")
    for era, stats in (result.get("eras") or {}).items():
        if stats:
            print(f"  {era:20s} n={stats['n']:5d}  RPS {stats['rps']} "
                  f"vs {stats['rps_baseline']}")
    print(f"skipped for no history: {result.get('skipped_no_history')}")
    print(f"wrote data-raw/ucl/{OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
